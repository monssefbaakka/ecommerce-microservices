package com.monssef.ecommerce.category;

import com.monssef.ecommerce.category.dto.CategoryDTO;
import com.monssef.ecommerce.category.dto.CategoryRequest;
import com.monssef.ecommerce.common.ResourceNotFoundException;
import lombok.RequiredArgsConstructor;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
@RequiredArgsConstructor            // constructor injection (generated by Lombok)
@Transactional(readOnly = true)     // read-only transaction by default
public class CategoryService {

    private final CategoryRepository repository;
    private final CategoryMapper mapper;

    public List<CategoryDTO> findAll() {
        return repository.findAll().stream()
                .map(mapper::toDto)
                .toList();
    }

    public CategoryDTO findById(Long id) {
        return mapper.toDto(findEntityById(id));
    }

    // Entity access for other services (e.g. ProductService needs the Category to link it)
    public Category findEntityById(Long id) {
        return repository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Category", id));
    }

    @Transactional
    public CategoryDTO create(CategoryRequest request) {
        if (repository.existsByNameIgnoreCase(request.getName())) {
            throw new ResponseStatusException(HttpStatus.CONFLICT,
                    "Category already exists: " + request.getName());
        }
        Category saved = repository.save(mapper.toEntity(request));
        return mapper.toDto(saved);
    }

    @Transactional
    public CategoryDTO update(Long id, CategoryRequest request) {
        Category category = repository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Category", id));
        boolean nameChanged = !category.getName().equalsIgnoreCase(request.getName());
        if (nameChanged && repository.existsByNameIgnoreCase(request.getName())) {
            throw new ResponseStatusException(HttpStatus.CONFLICT,
                    "Category already exists: " + request.getName());
        }
        mapper.update(request, category);
        return mapper.toDto(category); // managed entity: Hibernate saves the changes at commit
    }

    @Transactional
    public void delete(Long id) {
        Category category = repository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Category", id));
        try {
            repository.delete(category);
            repository.flush(); // runs the DELETE now so a foreign key violation is detected here
        } catch (DataIntegrityViolationException e) {
            throw new ResponseStatusException(HttpStatus.CONFLICT,
                    "Category is still used by products");
        }
    }
}
