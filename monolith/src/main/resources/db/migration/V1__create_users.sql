-- Accounts that log in with an email and a BCrypt password (#22).
-- Constraint names are the ones Hibernate generated before Flyway: a database created by
-- Hibernate and baselined (see application.yml) has exactly the same schema as a new one.
CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    email      VARCHAR(150)                NOT NULL,
    password   VARCHAR(255)                NOT NULL,
    role       VARCHAR(20)                 NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);
