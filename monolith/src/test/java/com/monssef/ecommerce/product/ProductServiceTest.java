package com.monssef.ecommerce.product;

import com.monssef.ecommerce.category.Category;
import com.monssef.ecommerce.category.CategoryService;
import com.monssef.ecommerce.common.ResourceNotFoundException;
import com.monssef.ecommerce.product.dto.ProductDTO;
import com.monssef.ecommerce.product.dto.ProductRequest;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mapstruct.factory.Mappers;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.Spy;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import java.math.BigDecimal;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class) // plain unit test: no Spring context, no database
class ProductServiceTest {

    private static final Pageable PAGE = PageRequest.of(0, 20);

    @Mock
    private ProductRepository productRepository;

    @Mock
    private CategoryService categoryService;

    @Spy // the real mapper, generated by MapStruct
    private ProductMapper mapper = Mappers.getMapper(ProductMapper.class);

    @InjectMocks
    private ProductService service;

    // --- Search: one repository method per combination of filters ---

    @Test
    void findAll_shouldListEverything_whenNoFilter() {
        when(productRepository.findAll(PAGE)).thenReturn(page(product(1L)));

        Page<ProductDTO> result = service.findAll(null, null, PAGE);

        assertThat(result.getContent()).extracting(ProductDTO::getId).containsExactly(1L);
    }

    @Test
    void findAll_shouldIgnoreBlankName() {
        when(productRepository.findAll(PAGE)).thenReturn(page(product(1L)));

        service.findAll("   ", null, PAGE);

        verify(productRepository).findAll(PAGE);
        verify(productRepository, never()).findByNameContainingIgnoreCase(any(), any());
    }

    @Test
    void findAll_shouldFilterByName() {
        when(productRepository.findByNameContainingIgnoreCase("phone", PAGE)).thenReturn(page(product(1L)));

        Page<ProductDTO> result = service.findAll("phone", null, PAGE);

        assertThat(result.getTotalElements()).isEqualTo(1);
    }

    @Test
    void findAll_shouldFilterByCategory() {
        when(productRepository.findByCategoryId(5L, PAGE)).thenReturn(page(product(1L)));

        Page<ProductDTO> result = service.findAll(null, 5L, PAGE);

        assertThat(result.getContent().get(0).getCategoryId()).isEqualTo(5L);
    }

    @Test
    void findAll_shouldFilterByNameAndCategory() {
        when(productRepository.findByNameContainingIgnoreCaseAndCategoryId("phone", 5L, PAGE))
                .thenReturn(page(product(1L)));

        Page<ProductDTO> result = service.findAll("phone", 5L, PAGE);

        assertThat(result.getTotalElements()).isEqualTo(1);
    }

    // --- Read one ---

    @Test
    void findById_shouldReturnProduct() {
        when(productRepository.findById(1L)).thenReturn(Optional.of(product(1L)));

        ProductDTO result = service.findById(1L);

        assertThat(result.getName()).isEqualTo("iPhone 15");
        assertThat(result.getStock()).isEqualTo(10);
    }

    @Test
    void findById_shouldThrow404_whenUnknown() {
        when(productRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.findById(99L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Product with id 99 not found");
    }

    // --- Writes ---

    @Test
    void create_shouldLinkCategoryAndSave() {
        Category category = category();
        when(categoryService.findEntityById(5L)).thenReturn(category);
        when(productRepository.save(any(Product.class))).thenAnswer(invocation -> {
            Product product = invocation.getArgument(0);
            product.setId(1L);
            return product;
        });

        ProductDTO result = service.create(request(5L));

        assertThat(result.getId()).isEqualTo(1L);
        assertThat(result.getCategoryId()).isEqualTo(5L);
        assertThat(result.getStock()).isEqualTo(3);
    }

    @Test
    void create_shouldThrow400_whenCategoryIdMissing() {
        assertThatThrownBy(() -> service.create(request(null)))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));

        verify(productRepository, never()).save(any());
    }

    @Test
    void create_shouldThrow404_whenCategoryUnknown() {
        when(categoryService.findEntityById(99L)).thenThrow(new ResourceNotFoundException("Category", 99L));

        assertThatThrownBy(() -> service.create(request(99L)))
                .isInstanceOf(ResourceNotFoundException.class);

        verify(productRepository, never()).save(any());
    }

    @Test
    void update_shouldCopyRequestAndSave() {
        Product existing = product(1L);
        when(productRepository.findById(1L)).thenReturn(Optional.of(existing));
        when(categoryService.findEntityById(5L)).thenReturn(category());
        when(productRepository.save(existing)).thenReturn(existing);

        ProductDTO result = service.update(1L, request(5L));

        assertThat(result.getId()).isEqualTo(1L);
        assertThat(result.getName()).isEqualTo("iPhone 16");
        assertThat(result.getPrice()).isEqualByComparingTo("1199.99");
        assertThat(result.getStock()).isEqualTo(3);
    }

    @Test
    void update_shouldThrow404_whenUnknown() {
        when(productRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.update(99L, request(5L)))
                .isInstanceOf(ResourceNotFoundException.class);

        verify(productRepository, never()).save(any());
    }

    @Test
    void delete_shouldDeleteExistingProduct() {
        Product existing = product(1L);
        when(productRepository.findById(1L)).thenReturn(Optional.of(existing));

        service.delete(1L);

        verify(productRepository).delete(existing);
    }

    @Test
    void delete_shouldThrow404_whenUnknown() {
        when(productRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.delete(99L))
                .isInstanceOf(ResourceNotFoundException.class);

        verify(productRepository, never()).delete(any());
    }

    private Page<Product> page(Product... products) {
        return new PageImpl<>(List.of(products), PAGE, products.length);
    }

    private Category category() {
        Category category = new Category();
        category.setId(5L);
        category.setName("Phones");
        return category;
    }

    private Product product(Long id) {
        Product product = new Product();
        product.setId(id);
        product.setName("iPhone 15");
        product.setPrice(new BigDecimal("999.99"));
        product.setStock(10);
        product.setCategory(category());
        return product;
    }

    private ProductRequest request(Long categoryId) {
        return new ProductRequest("iPhone 16", "256 GB", new BigDecimal("1199.99"), categoryId, 3);
    }
}
