package com.monssef.ecommerce.category;

import com.monssef.ecommerce.category.dto.CategoryDTO;
import com.monssef.ecommerce.category.dto.CategoryRequest;
import com.monssef.ecommerce.common.ResourceNotFoundException;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mapstruct.factory.Mappers;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.Spy;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class) // plain unit test: no Spring context, no database
class CategoryServiceTest {

    @Mock
    private CategoryRepository repository;

    @Spy // the real mapper, generated by MapStruct
    private CategoryMapper mapper = Mappers.getMapper(CategoryMapper.class);

    @InjectMocks
    private CategoryService service;

    @Test
    void findAll_shouldMapEveryCategory() {
        when(repository.findAll()).thenReturn(List.of(
                category(1L, "Phones"), category(2L, "Laptops")));

        List<CategoryDTO> result = service.findAll();

        assertThat(result).extracting(CategoryDTO::getName).containsExactly("Phones", "Laptops");
    }

    @Test
    void findById_shouldReturnCategory() {
        when(repository.findById(1L)).thenReturn(Optional.of(category(1L, "Phones")));

        CategoryDTO result = service.findById(1L);

        assertThat(result.getId()).isEqualTo(1L);
        assertThat(result.getName()).isEqualTo("Phones");
    }

    @Test
    void findById_shouldThrow404_whenUnknown() {
        when(repository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.findById(99L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Category with id 99 not found");
    }

    @Test
    void create_shouldSaveCategory() {
        when(repository.existsByNameIgnoreCase("Phones")).thenReturn(false);
        when(repository.save(any(Category.class))).thenAnswer(invocation -> {
            Category category = invocation.getArgument(0);
            category.setId(1L);
            return category;
        });

        CategoryDTO result = service.create(new CategoryRequest("Phones", "Smartphones"));

        ArgumentCaptor<Category> captor = ArgumentCaptor.forClass(Category.class);
        verify(repository).save(captor.capture());
        assertThat(captor.getValue().getName()).isEqualTo("Phones");
        assertThat(captor.getValue().getDescription()).isEqualTo("Smartphones");
        assertThat(result.getId()).isEqualTo(1L);
    }

    @Test
    void create_shouldThrow409_whenNameAlreadyUsed() {
        when(repository.existsByNameIgnoreCase("Phones")).thenReturn(true);

        assertThatThrownBy(() -> service.create(new CategoryRequest("Phones", null)))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.CONFLICT));

        verify(repository, never()).save(any());
    }

    @Test
    void update_shouldChangeManagedEntity() {
        Category category = category(1L, "Phones");
        when(repository.findById(1L)).thenReturn(Optional.of(category));
        when(repository.existsByNameIgnoreCase("Smartphones")).thenReturn(false);

        CategoryDTO result = service.update(1L, new CategoryRequest("Smartphones", "All phones"));

        assertThat(category.getName()).isEqualTo("Smartphones");
        assertThat(category.getDescription()).isEqualTo("All phones");
        assertThat(result.getId()).isEqualTo(1L);
        verify(repository, never()).save(any()); // dirty checking saves it at commit
    }

    @Test
    void update_shouldAllowSameNameWithOtherCase() {
        Category category = category(1L, "Phones");
        when(repository.findById(1L)).thenReturn(Optional.of(category));

        CategoryDTO result = service.update(1L, new CategoryRequest("PHONES", null));

        assertThat(result.getName()).isEqualTo("PHONES");
        verify(repository, never()).existsByNameIgnoreCase(any());
    }

    @Test
    void update_shouldThrow409_whenNewNameAlreadyUsed() {
        Category category = category(1L, "Phones");
        when(repository.findById(1L)).thenReturn(Optional.of(category));
        when(repository.existsByNameIgnoreCase("Laptops")).thenReturn(true);

        assertThatThrownBy(() -> service.update(1L, new CategoryRequest("Laptops", null)))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.CONFLICT));

        assertThat(category.getName()).isEqualTo("Phones");
    }

    @Test
    void update_shouldThrow404_whenUnknown() {
        when(repository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.update(99L, new CategoryRequest("Phones", null)))
                .isInstanceOf(ResourceNotFoundException.class);
    }

    @Test
    void delete_shouldDeleteAndFlush() {
        Category category = category(1L, "Phones");
        when(repository.findById(1L)).thenReturn(Optional.of(category));

        service.delete(1L);

        verify(repository).delete(category);
        verify(repository).flush();
    }

    @Test
    void delete_shouldThrow409_whenStillUsedByProducts() {
        when(repository.findById(1L)).thenReturn(Optional.of(category(1L, "Phones")));
        doThrow(new DataIntegrityViolationException("fk_products_category")).when(repository).flush();

        assertThatThrownBy(() -> service.delete(1L))
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("Category is still used by products")
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.CONFLICT));
    }

    @Test
    void delete_shouldThrow404_whenUnknown() {
        when(repository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.delete(99L))
                .isInstanceOf(ResourceNotFoundException.class);

        verify(repository, never()).delete(any());
    }

    private Category category(Long id, String name) {
        Category category = new Category();
        category.setId(id);
        category.setName(name);
        return category;
    }
}
