-- Payments of an order, accepted or declined (#45). Only the last 4 digits of the card are kept.
-- order_id points to order-service, another database: no foreign key, only the value.
-- Constraint names are the ones Hibernate generated before Flyway: a database created by
-- Hibernate and baselined (see application.yml) has exactly the same schema as a new one.
CREATE TABLE payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    amount     NUMERIC(12, 2)              NOT NULL,
    card_last4 VARCHAR(4)                  NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    order_id   BIGINT                      NOT NULL,
    status     VARCHAR(20)                 NOT NULL,
    user_email VARCHAR(150)                NOT NULL,
    CONSTRAINT payments_pkey PRIMARY KEY (id),
    CONSTRAINT payments_status_check CHECK (status IN ('SUCCEEDED', 'DECLINED'))
);
