-- The payment-service schema as Hibernate created it before Flyway (#115): the DDL that
-- ddl-auto: update runs on an empty database, written out by Hibernate
-- (jakarta.persistence.schema-generation.scripts.action=update). The databases created
-- before Flyway hold exactly these tables. FlywayMigrationIT loads it and baselines it.

create table payments (id bigint generated by default as identity, amount numeric(12,2) not null, card_last4 varchar(4) not null, created_at timestamp(6) with time zone not null, order_id bigint not null, status varchar(20) not null check ((status in ('SUCCEEDED','DECLINED'))), user_email varchar(150) not null, primary key (id));
