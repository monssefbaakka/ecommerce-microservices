package com.monssef.orderservice.cart;

import com.monssef.orderservice.cart.dto.AddCartItemRequest;
import com.monssef.orderservice.cart.dto.CartDTO;
import com.monssef.orderservice.cart.dto.UpdateCartItemRequest;
import com.monssef.orderservice.client.ServiceUnavailableException;
import com.monssef.orderservice.common.ResourceNotFoundException;
import com.monssef.orderservice.product.InsufficientStockException;
import com.monssef.orderservice.product.ProductClient;
import com.monssef.orderservice.product.ProductInfo;
import com.monssef.orderservice.product.ProductSnapshot;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mapstruct.factory.Mappers;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.Spy;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import java.math.BigDecimal;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class) // plain unit test: no Spring context, no database, no product-service
class CartServiceTest {

    private static final String EMAIL = "john@example.com";
    private static final ProductInfo PHONE = product(1L, "iPhone 15", "999.99", 10);
    private static final ProductInfo CASE = product(2L, "Case", "19.90", 10);

    @Mock
    private CartRepository cartRepository;

    @Mock
    private ProductClient productClient;

    @Spy // the real mapper, generated by MapStruct
    private CartMapper mapper = Mappers.getMapper(CartMapper.class);

    @InjectMocks
    private CartService service;

    @Test
    void getCart_shouldReturnEmptyCart_whenUserHasNone() {
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.empty());

        CartDTO result = service.getCart(EMAIL);

        assertThat(result.getItems()).isEmpty();
        assertThat(result.getTotalQuantity()).isZero();
        assertThat(result.getTotal()).isEqualByComparingTo("0");
        verify(cartRepository, never()).save(any());
        verifyNoInteractions(productClient);
    }

    @Test
    void getCart_shouldComputeSubtotalsAndTotal_withOneCallToProductService() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        cart.addItem(2L, 1);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAllOrLastKnown(List.of(1L, 2L))).thenReturn(upToDate(Map.of(1L, PHONE, 2L, CASE)));

        CartDTO result = service.getCart(EMAIL);

        assertThat(result.getItems()).hasSize(2);
        assertThat(result.getItems().get(0).getProductName()).isEqualTo("iPhone 15");
        assertThat(result.getItems().get(0).getSubtotal()).isEqualByComparingTo("1999.98");
        assertThat(result.getTotalQuantity()).isEqualTo(3);
        assertThat(result.getTotal()).isEqualByComparingTo("2019.88");
        verify(productClient, times(1)).findAllOrLastKnown(any());
    }

    @Test
    void getCart_shouldLeaveOutProductsDeletedInProductService() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        cart.addItem(2L, 1);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAllOrLastKnown(List.of(1L, 2L))).thenReturn(upToDate(Map.of(2L, CASE)));

        CartDTO result = service.getCart(EMAIL);

        assertThat(result.getItems()).extracting("productId").containsExactly(2L);
        assertThat(result.getTotal()).isEqualByComparingTo("19.90");
    }

    @Test
    void getCart_shouldShowLastKnownNamesAndPrices_whenProductServiceIsUnavailable() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAllOrLastKnown(List.of(1L)))
                .thenReturn(new ProductSnapshot(Map.of(1L, PHONE), false));

        CartDTO result = service.getCart(EMAIL);

        assertThat(result.isProductsUpToDate()).isFalse();
        assertThat(result.getItems().get(0).getProductName()).isEqualTo("iPhone 15");
        assertThat(result.getTotal()).isEqualByComparingTo("1999.98");
    }

    @Test
    void removeItem_shouldStillRemoveTheLine_whenProductServiceIsUnavailable() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        cart.addItem(2L, 1);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAllOrLastKnown(List.of(2L))).thenReturn(new ProductSnapshot(Map.of(), false));

        CartDTO result = service.removeItem(EMAIL, 1L);

        assertThat(cart.getProductIds()).containsExactly(2L);
        assertThat(result.isProductsUpToDate()).isFalse();
        assertThat(result.getItems()).extracting("productId").containsExactly(2L);
        assertThat(result.getTotal()).isNull();   // the price of the case was never seen
    }

    @Test
    void addItem_shouldCreateCartForTheEmail_whenUserHasNone() {
        when(productClient.find(1L)).thenReturn(PHONE);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.empty());
        when(cartRepository.save(any(Cart.class))).thenAnswer(invocation -> invocation.getArgument(0));
        when(productClient.findAllOrLastKnown(List.of(1L))).thenReturn(upToDate(Map.of(1L, PHONE)));

        CartDTO result = service.addItem(EMAIL, new AddCartItemRequest(1L, 2));

        ArgumentCaptor<Cart> captor = ArgumentCaptor.forClass(Cart.class);
        verify(cartRepository).save(captor.capture());
        assertThat(captor.getValue().getUserEmail()).isEqualTo(EMAIL);
        assertThat(result.getItems()).hasSize(1);
        assertThat(result.getItems().get(0).getQuantity()).isEqualTo(2);
        assertThat(result.getTotal()).isEqualByComparingTo("1999.98");
    }

    @Test
    void addItem_shouldIncreaseQuantity_whenProductAlreadyInCart() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(productClient.find(1L)).thenReturn(PHONE);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(cartRepository.save(cart)).thenReturn(cart);
        when(productClient.findAllOrLastKnown(List.of(1L))).thenReturn(upToDate(Map.of(1L, PHONE)));

        CartDTO result = service.addItem(EMAIL, new AddCartItemRequest(1L, 3));

        assertThat(result.getItems()).hasSize(1); // same line, not a second one
        assertThat(result.getItems().get(0).getQuantity()).isEqualTo(5);
    }

    @Test
    void addItem_shouldReturn400_whenTotalQuantityExceedsMax() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, CartService.MAX_QUANTITY);
        when(productClient.find(1L)).thenReturn(product(1L, "iPhone 15", "999.99", 500));
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));

        assertThatThrownBy(() -> service.addItem(EMAIL, new AddCartItemRequest(1L, 1)))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.BAD_REQUEST);

        verify(cartRepository, never()).save(any());
    }

    @Test
    void addItem_shouldThrow409_whenNotEnoughStock() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(productClient.find(1L)).thenReturn(product(1L, "iPhone 15", "999.99", 3));
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));

        // 2 already in the cart + 2 more = 4, only 3 left
        assertThatThrownBy(() -> service.addItem(EMAIL, new AddCartItemRequest(1L, 2)))
                .isInstanceOf(InsufficientStockException.class)
                .hasMessageContaining("Not enough stock for product 1 (iPhone 15): 3 left")
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.CONFLICT);

        assertThat(cart.getItems().get(0).getQuantity()).isEqualTo(2);
        verify(cartRepository, never()).save(any());
    }

    @Test
    void addItem_shouldThrow409_whenProductOutOfStock() {
        when(productClient.find(1L)).thenReturn(product(1L, "iPhone 15", "999.99", 0));
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(new Cart(EMAIL)));

        assertThatThrownBy(() -> service.addItem(EMAIL, new AddCartItemRequest(1L, 1)))
                .isInstanceOf(InsufficientStockException.class);

        verify(cartRepository, never()).save(any());
    }

    @Test
    void addItem_shouldPassOn404_whenProductDoesNotExist() {
        when(productClient.find(99L)).thenThrow(new ResourceNotFoundException("Product", 99L));

        assertThatThrownBy(() -> service.addItem(EMAIL, new AddCartItemRequest(99L, 1)))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Product with id 99 not found");

        verifyNoInteractions(cartRepository);
    }

    @Test
    void addItem_shouldPassOn503_whenProductServiceIsDown() {
        when(productClient.find(1L))
                .thenThrow(new ServiceUnavailableException("Product service"));

        assertThatThrownBy(() -> service.addItem(EMAIL, new AddCartItemRequest(1L, 1)))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.SERVICE_UNAVAILABLE);

        verifyNoInteractions(cartRepository);
    }

    @Test
    void updateItem_shouldReplaceQuantity() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.find(1L)).thenReturn(PHONE);
        when(productClient.findAllOrLastKnown(List.of(1L))).thenReturn(upToDate(Map.of(1L, PHONE)));

        CartDTO result = service.updateItem(EMAIL, 1L, new UpdateCartItemRequest(7));

        assertThat(result.getItems().get(0).getQuantity()).isEqualTo(7);
    }

    @Test
    void updateItem_shouldThrow409_whenNotEnoughStock() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.find(1L)).thenReturn(PHONE); // stock 10

        assertThatThrownBy(() -> service.updateItem(EMAIL, 1L, new UpdateCartItemRequest(11)))
                .isInstanceOf(InsufficientStockException.class);

        assertThat(cart.getItems().get(0).getQuantity()).isEqualTo(2);
    }

    @Test
    void updateItem_shouldThrow404_whenProductNotInCart() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));

        assertThatThrownBy(() -> service.updateItem(EMAIL, 2L, new UpdateCartItemRequest(1)))
                .isInstanceOf(ResourceNotFoundException.class);

        verifyNoInteractions(productClient);
    }

    @Test
    void removeItem_shouldRemoveOnlyThatProduct() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        cart.addItem(2L, 1);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAllOrLastKnown(List.of(2L))).thenReturn(upToDate(Map.of(2L, CASE)));

        CartDTO result = service.removeItem(EMAIL, 1L);

        assertThat(result.getItems()).hasSize(1);
        assertThat(result.getItems().get(0).getProductId()).isEqualTo(2L);
        assertThat(cart.getItems()).hasSize(1);
    }

    @Test
    void removeItem_shouldThrow404_whenUserHasNoCart() {
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.removeItem(EMAIL, 1L))
                .isInstanceOf(ResourceNotFoundException.class);
    }

    @Test
    void clear_shouldRemoveAllItems_withoutCallingProductService() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(cartRepository.findByUserEmail(EMAIL)).thenReturn(Optional.of(cart));

        service.clear(EMAIL);

        assertThat(cart.getItems()).isEmpty();
        verifyNoInteractions(productClient);
    }

    private static ProductSnapshot upToDate(Map<Long, ProductInfo> products) {
        return new ProductSnapshot(products, true);
    }

    private static ProductInfo product(Long id, String name, String price, int stock) {
        return new ProductInfo(id, name, new BigDecimal(price), stock);
    }
}
