package com.monssef.orderservice.order;

import com.monssef.orderservice.cart.Cart;
import com.monssef.orderservice.cart.CartRepository;
import com.monssef.orderservice.client.ServiceUnavailableException;
import com.monssef.orderservice.common.BusinessMetrics;
import com.monssef.orderservice.common.ResourceNotFoundException;
import com.monssef.orderservice.order.dto.OrderDTO;
import com.monssef.orderservice.order.dto.OrderSummaryDTO;
import com.monssef.orderservice.product.ProductClient;
import com.monssef.orderservice.product.ProductInfo;
import com.monssef.orderservice.product.ReservedItem;
import com.monssef.orderservice.product.StockLine;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mapstruct.factory.Mappers;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.Spy;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import java.math.BigDecimal;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class) // plain unit test: no Spring context, no database, no product-service
class OrderServiceTest {

    private static final String EMAIL = "john@example.com";
    private static final ProductInfo PHONE = new ProductInfo(1L, "iPhone 15", new BigDecimal("999.99"), 10);
    private static final ProductInfo CASE = new ProductInfo(2L, "Case", new BigDecimal("19.90"), 10);

    @Mock
    private OrderRepository orderRepository;

    @Mock
    private CartRepository cartRepository;

    @Mock
    private ProductClient productClient;

    @Spy // the real mapper, generated by MapStruct
    private OrderMapper mapper = Mappers.getMapper(OrderMapper.class);

    @Mock
    private BusinessMetrics metrics;

    @InjectMocks
    private OrderService service;

    @Test
    void placeOrder_shouldReserveTheCartAndCopyWhatWasReserved() {
        Cart cart = cartWithPhoneAndCase();
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(List.of(1L, 2L))).thenReturn(Map.of(1L, PHONE, 2L, CASE));
        when(productClient.reserve(List.of(new StockLine(1L, 2), new StockLine(2L, 1)))).thenReturn(List.of(
                new ReservedItem(1L, "iPhone 15", new BigDecimal("999.99"), 2),
                new ReservedItem(2L, "Case", new BigDecimal("19.90"), 1)));
        when(orderRepository.saveAndFlush(any(Order.class))).thenAnswer(invocation -> invocation.getArgument(0));

        OrderDTO result = service.placeOrder(EMAIL);

        ArgumentCaptor<Order> captor = ArgumentCaptor.forClass(Order.class);
        verify(orderRepository).saveAndFlush(captor.capture());
        assertThat(captor.getValue().getUserEmail()).isEqualTo(EMAIL);
        assertThat(result.getStatus()).isEqualTo(OrderStatus.PENDING);
        assertThat(result.getItems()).hasSize(2);
        assertThat(result.getItems().get(0).getProductId()).isEqualTo(1L);
        assertThat(result.getItems().get(0).getProductName()).isEqualTo("iPhone 15");
        assertThat(result.getItems().get(0).getUnitPrice()).isEqualByComparingTo("999.99");
        assertThat(result.getItems().get(0).getSubtotal()).isEqualByComparingTo("1999.98");
        assertThat(result.getTotalQuantity()).isEqualTo(3);
        assertThat(result.getTotal()).isEqualByComparingTo("2019.88");
        verify(productClient, never()).release(any());
    }

    @Test
    void placeOrder_shouldEmptyTheCart() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(List.of(1L))).thenReturn(Map.of(1L, PHONE));
        when(productClient.reserve(any()))
                .thenReturn(List.of(new ReservedItem(1L, "iPhone 15", new BigDecimal("999.99"), 2)));
        when(orderRepository.saveAndFlush(any(Order.class))).thenAnswer(invocation -> invocation.getArgument(0));

        OrderDTO result = service.placeOrder(EMAIL);

        assertThat(cart.getItems()).isEmpty();
        assertThat(result.getItems()).hasSize(1); // the order keeps its lines
        verify(metrics).orderPlaced();
    }

    @Test
    void placeOrder_shouldDropProductsDeletedSince_beforeReserving() {
        Cart cart = cartWithPhoneAndCase();
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(List.of(1L, 2L))).thenReturn(Map.of(2L, CASE)); // the phone was deleted
        when(productClient.reserve(List.of(new StockLine(2L, 1))))
                .thenReturn(List.of(new ReservedItem(2L, "Case", new BigDecimal("19.90"), 1)));
        when(orderRepository.saveAndFlush(any(Order.class))).thenAnswer(invocation -> invocation.getArgument(0));

        OrderDTO result = service.placeOrder(EMAIL);

        assertThat(result.getItems()).extracting("productId").containsExactly(2L);
        assertThat(result.getTotal()).isEqualByComparingTo("19.90");
    }

    @Test
    void placeOrder_shouldThrow400_whenEveryProductWasDeleted() {
        Cart cart = cartWithPhoneAndCase();
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(List.of(1L, 2L))).thenReturn(Map.of());

        assertThatThrownBy(() -> service.placeOrder(EMAIL))
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("Cart is empty");

        verify(productClient, never()).reserve(any());
        verifyNoInteractions(orderRepository);
    }

    @Test
    void placeOrder_shouldPassOn409AndKeepCart_whenProductServiceLacksStock() {
        Cart cart = cartWithPhoneAndCase();
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(List.of(1L, 2L))).thenReturn(Map.of(1L, PHONE, 2L, CASE));
        when(productClient.reserve(any())).thenThrow(new ResponseStatusException(HttpStatus.CONFLICT,
                "Not enough stock for product 1 (iPhone 15): 1 left"));

        assertThatThrownBy(() -> service.placeOrder(EMAIL))
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("Not enough stock for product 1 (iPhone 15): 1 left")
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.CONFLICT);

        assertThat(cart.getItems()).hasSize(2);
        verify(productClient, never()).release(any()); // nothing was taken
        verifyNoInteractions(orderRepository, metrics);
    }

    @Test
    void placeOrder_shouldPassOn503AndKeepCart_whenProductServiceIsDown() {
        Cart cart = cartWithPhoneAndCase();
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(any()))
                .thenThrow(new ServiceUnavailableException("Product service"));

        assertThatThrownBy(() -> service.placeOrder(EMAIL))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.SERVICE_UNAVAILABLE);

        assertThat(cart.getItems()).hasSize(2);
        verifyNoInteractions(orderRepository);
    }

    @Test
    void placeOrder_shouldGiveTheStockBack_whenTheOrderCannotBeSaved() {
        Cart cart = cartWithPhoneAndCase();
        List<StockLine> lines = List.of(new StockLine(1L, 2), new StockLine(2L, 1));
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(cart));
        when(productClient.findAll(List.of(1L, 2L))).thenReturn(Map.of(1L, PHONE, 2L, CASE));
        when(productClient.reserve(lines)).thenReturn(List.of(
                new ReservedItem(1L, "iPhone 15", new BigDecimal("999.99"), 2),
                new ReservedItem(2L, "Case", new BigDecimal("19.90"), 1)));
        when(orderRepository.saveAndFlush(any(Order.class))).thenThrow(new DataIntegrityViolationException("boom"));

        assertThatThrownBy(() -> service.placeOrder(EMAIL))
                .isInstanceOf(DataIntegrityViolationException.class);

        verify(productClient).release(lines);
        assertThat(cart.getItems()).hasSize(2);
        verifyNoInteractions(metrics); // the stock was given back: no order to count
    }

    @Test
    void placeOrder_shouldThrow400_whenCartIsEmpty() {
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.of(new Cart(EMAIL)));

        assertThatThrownBy(() -> service.placeOrder(EMAIL))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.BAD_REQUEST);

        verify(productClient, never()).reserve(any());
        verifyNoInteractions(orderRepository);
    }

    @Test
    void placeOrder_shouldThrow400_whenUserHasNoCart() {
        when(cartRepository.findForUpdateByUserEmail(EMAIL)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.placeOrder(EMAIL))
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("Cart is empty");

        verifyNoInteractions(orderRepository, productClient);
    }

    @Test
    void findAll_shouldReturnOrdersOfUserOnly() {
        Order order = order(7L);
        Pageable pageable = PageRequest.of(0, 10);
        when(orderRepository.findByUserEmail(EMAIL, pageable))
                .thenReturn(new PageImpl<>(List.of(order), pageable, 1));

        Page<OrderDTO> result = service.findAll(EMAIL, pageable);

        assertThat(result.getTotalElements()).isEqualTo(1);
        assertThat(result.getContent().get(0).getId()).isEqualTo(7L);
        assertThat(result.getContent().get(0).getTotal()).isEqualByComparingTo("1999.98");
    }

    @Test
    void findAll_shouldReturnEmptyPage_whenNoOrders() {
        Pageable pageable = PageRequest.of(0, 10);
        when(orderRepository.findByUserEmail(EMAIL, pageable)).thenReturn(Page.empty(pageable));

        assertThat(service.findAll(EMAIL, pageable).getContent()).isEmpty();
    }

    @Test
    void findById_shouldReturnOrderOfUser() {
        when(orderRepository.findByIdAndUserEmail(7L, EMAIL)).thenReturn(Optional.of(order(7L)));

        OrderDTO result = service.findById(EMAIL, 7L);

        assertThat(result.getId()).isEqualTo(7L);
        assertThat(result.getTotal()).isEqualByComparingTo("1999.98");
    }

    @Test
    void findById_shouldThrow404_whenOrderMissingOrOfAnotherUser() {
        when(orderRepository.findByIdAndUserEmail(7L, EMAIL)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.findById(EMAIL, 7L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Order with id 7 not found");
    }

    @Test
    void findSummary_shouldReturnOwnerStatusAndTotal() {
        when(orderRepository.findById(7L)).thenReturn(Optional.of(order(7L)));

        OrderSummaryDTO result = service.findSummary(7L);

        assertThat(result.getId()).isEqualTo(7L);
        assertThat(result.getUserEmail()).isEqualTo(EMAIL);
        assertThat(result.getStatus()).isEqualTo(OrderStatus.PENDING);
        assertThat(result.getTotal()).isEqualByComparingTo("1999.98");
    }

    @Test
    void findSummary_shouldThrow404_whenOrderMissing() {
        when(orderRepository.findById(7L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.findSummary(7L))
                .isInstanceOf(ResourceNotFoundException.class);
    }

    @Test
    void markPaid_shouldSwitchPendingOrderToPaid() {
        Order order = order(7L);
        when(orderRepository.findForUpdateById(7L)).thenReturn(Optional.of(order));

        OrderSummaryDTO result = service.markPaid(7L);

        assertThat(order.getStatus()).isEqualTo(OrderStatus.PAID);
        assertThat(result.getStatus()).isEqualTo(OrderStatus.PAID);
    }

    @Test
    void markPaid_shouldThrow409_whenOrderAlreadyPaid() {
        Order order = order(7L);
        order.setStatus(OrderStatus.PAID);
        when(orderRepository.findForUpdateById(7L)).thenReturn(Optional.of(order));

        assertThatThrownBy(() -> service.markPaid(7L))
                .isInstanceOf(ResponseStatusException.class)
                .hasMessageContaining("Order 7 is PAID, only a PENDING order can be paid")
                .extracting(ex -> ((ResponseStatusException) ex).getStatusCode())
                .isEqualTo(HttpStatus.CONFLICT);
    }

    @Test
    void markPaid_shouldThrow404_whenOrderMissing() {
        when(orderRepository.findForUpdateById(7L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.markPaid(7L))
                .isInstanceOf(ResourceNotFoundException.class);
    }

    private Cart cartWithPhoneAndCase() {
        Cart cart = new Cart(EMAIL);
        cart.addItem(1L, 2);
        cart.addItem(2L, 1);
        return cart;
    }

    private Order order(Long id) {
        Order order = new Order(EMAIL);
        order.setId(id);
        order.addItem(new ReservedItem(1L, "iPhone 15", new BigDecimal("999.99"), 2));
        return order;
    }
}
