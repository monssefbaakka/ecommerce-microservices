-- Orders with a copy of each product's name and price at purchase time (#44).
-- payment-service moves them from PENDING to PAID
CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status     VARCHAR(20)                 NOT NULL,
    total      NUMERIC(12, 2)              NOT NULL,
    user_email VARCHAR(150)                NOT NULL,
    CONSTRAINT orders_pkey PRIMARY KEY (id),
    CONSTRAINT orders_status_check CHECK (status IN ('PENDING', 'PAID', 'CANCELLED'))
);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id   BIGINT         NOT NULL,
    product_name VARCHAR(150)   NOT NULL,
    quantity     INTEGER        NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,
    order_id     BIGINT         NOT NULL,
    CONSTRAINT order_items_pkey PRIMARY KEY (id),
    CONSTRAINT order_items_quantity_check CHECK (quantity >= 1),
    CONSTRAINT fkbioxgbv59vetrxe0ejfubep1w FOREIGN KEY (order_id) REFERENCES orders (id)
);
