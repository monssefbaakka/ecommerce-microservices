-- One cart per user, found by the email of the JWT: the accounts live in auth-service (#44).
-- product_id points to product-service, another database: no foreign key, only the value.
-- Constraint names are the ones Hibernate generated before Flyway: a database created by
-- Hibernate and baselined (see application.yml) has exactly the same schema as a new one.
CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_email VARCHAR(150) NOT NULL,
    CONSTRAINT carts_pkey PRIMARY KEY (id),
    CONSTRAINT ukj32fvm6dplkq8v924ynx105l6 UNIQUE (user_email)
);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT  NOT NULL,
    quantity   INTEGER NOT NULL,
    cart_id    BIGINT  NOT NULL,
    CONSTRAINT cart_items_pkey PRIMARY KEY (id),
    CONSTRAINT uk6oue0maw421roerltnxn16a38 UNIQUE (cart_id, product_id),
    CONSTRAINT cart_items_quantity_check CHECK (quantity >= 1),
    CONSTRAINT fkpcttvuq4mxppo8sxggjtn5i2c FOREIGN KEY (cart_id) REFERENCES carts (id)
);
