package com.monssef.productservice.category;

import com.monssef.productservice.category.dto.CategoryDTO;
import com.monssef.productservice.category.dto.CategoryRequest;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;

@Mapper(componentModel = "spring")
public interface CategoryMapper {

    CategoryDTO toDto(Category category);

    @Mapping(target = "id", ignore = true) // generated by the database
    Category toEntity(CategoryRequest request);

    // Copies the request onto a managed entity: Hibernate saves the changes at commit
    @Mapping(target = "id", ignore = true)
    void update(CategoryRequest request, @MappingTarget Category category);
}
